"""Regenerate frontend/src/api/types.gen.ts from backend/app/models.py.

Usage (repo root, backend venv):  backend/.venv/Scripts/python scripts/gen_types.py [--check]
--check exits 1 without writing when the file on disk is stale (the backend tests call this).
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.models import contract_json_schema  # noqa: E402

OUT = ROOT / "frontend" / "src" / "api" / "types.gen.ts"
BANNER = "/* Generated by scripts/gen_types.py from backend/app/models.py. Do not edit by hand. */\n\n"


def _strip_nested_titles(node, keep: bool = False):
    """json2ts turns every titled sub-schema into its own named type; keep titles on $defs only."""
    if isinstance(node, dict):
        return {k: _strip_nested_titles(v) for k, v in node.items() if keep or k != "title"}
    if isinstance(node, list):
        return [_strip_nested_titles(v) for v in node]
    return node


def build_schema() -> dict:
    defs = contract_json_schema()["$defs"]
    defs = {name: {**_strip_nested_titles(body, keep=False), "title": name} for name, body in defs.items()}
    return {
        "title": "Contract",
        "type": "object",
        "additionalProperties": False,
        "properties": {"server": {"$ref": "#/$defs/ServerContract"}, "client": {"$ref": "#/$defs/ClientContract"}},
        "required": ["server", "client"],
        "$defs": defs,
    }


def generate() -> str:
    bin_name = "json2ts.cmd" if os.name == "nt" else "json2ts"
    json2ts = ROOT / "frontend" / "node_modules" / ".bin" / bin_name
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "contract.json"
        src.write_text(json.dumps(build_schema()), encoding="utf-8")
        result = subprocess.run(
            [str(json2ts), "--input", str(src), "--bannerComment", "", "--additionalProperties", "false", "--unreachableDefinitions"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            shell=os.name == "nt",
        )
    if result.returncode != 0:
        raise SystemExit(f"json2ts failed:\n{result.stderr}")
    return BANNER + result.stdout.replace("\r\n", "\n")


def main() -> int:
    text = generate()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in sys.argv:
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/gen_types.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
